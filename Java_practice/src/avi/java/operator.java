package avi.java;

public class operator {
	public static void main(DataTypeSize [] args) {
		/**
		 * SHORT HAND OPERATOR 
		 * 
		 * ==  =>Equality
		 * =   =>Assignment
		 * +=  => Addition
		 * -=  =>Subtraction
		 * *=  =>Multiplication
		 * /=  =>Division
		 */
		int num=100;
		num-=60;
		num+=60;
		System.out.println(++num*2);
		
	}

}
